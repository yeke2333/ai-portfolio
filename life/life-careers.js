function weightedPick(options,roll,environment){
  const weight=category=>category===environment&&environment?2:1;
  let target=roll*options.reduce((total,option)=>total+weight(option.environment),0);
  for(const option of options){
    target-=weight(option.environment);
    if(target<0)return option;
  }
  return options.at(-1);
}

export function familyCareer(birthYear,roll,rural){
  const candidates=backgrounds.filter(([, ,start, , ,from])=>!from||birthYear+start>=from)
    .map(([education,job,start,firstJob,environment])=>({education,job,start,firstJob,environment}));
  return weightedPick(candidates,roll,rural?'rural':'urban');
}

