export function occupationAt(person){
  const pool=professions[person.careerTrack]??professions.入门;
  const year=(person.birthYear??2002)+person.age;
  const options=pool.map(entry=>Array.isArray(entry)?entry:[entry,0])
    .filter(([,from])=>year>=from)
    .map(([job,,environment])=>({job,environment}));
  let value=(person.identitySeed??person.rng)^(person.city??person.birthCity??0);
  value=Math.imul(value^(value>>>16),0x7feb352d);
  value=Math.imul(value^(value>>>15),0x846ca68b);
  const roll=((value^(value>>>16))>>>0)/4294967296;
  return weightedPick(options,roll,person.place===3?'rural':'urban').job;
}
